/** Generates docs/API.md from the Fastify route definitions (method + path + nearest doc comment). */
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

const dir = path.resolve("apps/api/src/routes");
const titles: Record<string, string> = {
  auth: "Auth & emergency stop", system: "System, providers, notifications, audit log", projects: "Projects, wizard, dashboard, policy",
  integrations: "Integrations & OAuth", media: "Media assets", content: "Campaigns, posts, calendar, queues",
  engagement: "Inbox, analytics, Discover, opportunities", operations: "Website, code changes, deployments, agents, approvals, automations",
  events: "Server-sent events", public: "Public signed media (no /api prefix)",
};
let out = `# HTTP API\n\nAll routes are prefixed with \`/api\` (except signed public media). Authentication uses the \`sp_session\` httpOnly cookie. Every state-changing request must send \`x-socialpilot-csrf: 1\`. Errors return \`{ error, code, details? }\` (\`setup_required\`, \`confirmation_required\`, \`budget_exceeded\`, \`emergency_stop\`, \`asset_busy\`, …). Request bodies are validated with the zod schemas in \`packages/shared/src/schemas.ts\`.\n\nProject-scoped routes (\`/projects/:projectId/...\`) verify ownership and return 404 for other users' projects.\n\n_Generated by \`npx tsx scripts/gen-api-docs.ts\`._\n`;
for (const file of readdirSync(dir).filter((f) => f.endsWith(".ts")).sort()) {
  const src = readFileSync(path.join(dir, file), "utf8").split("\n");
  const rows: string[] = [];
  src.forEach((line, i) => {
    const m = line.match(/app\.(get|post|put|patch|delete)\(\s*"([^"]+)"/);
    if (!m) return;
    let doc = "";
    for (let j = i - 1; j >= Math.max(0, i - 3); j--) {
      const d = src[j].match(/\/\*\*\s*(.+?)\s*\*\//) ?? src[j].match(/\/\/\s*───── (.+?) ─/);
      if (d) { doc = d[1]; break; }
    }
    rows.push(`| \`${m[1].toUpperCase()}\` | \`${file === "public.ts" ? "" : "/api"}${m[2]}\` | ${doc} |`);
  });
  if (rows.length) out += `\n## ${titles[file.replace(".ts", "")] ?? file}\n\n| Method | Path | Notes |\n|---|---|---|\n${rows.join("\n")}\n`;
}
writeFileSync("docs/API.md", out);
console.log("docs/API.md written");
